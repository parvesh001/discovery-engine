import { readFile, writeFile } from 'node:fs/promises';

export type ReportSection = 'EVAL_RESULTS' | 'COST_MODEL';

const SECTION_TITLES: Record<ReportSection, string> = {
  EVAL_RESULTS: 'Eval Results',
  COST_MODEL: 'Cost Model',
};

function marker(section: ReportSection): { start: string; end: string } {
  return { start: `<!-- ${section} -->`, end: `<!-- /${section} -->` };
}

/**
 * Pure string transform (no file I/O) so `runEvals.ts` and `costModel.ts` can each own one
 * clearly delimited section of EVAL_REPORT.md without clobbering the other script's output
 * on re-run (spec 09, item 5: the report is generated by "the scripts", plural). Replaces
 * the section in place if its markers already exist, otherwise appends a new section.
 */
export function upsertSection(existingContent: string, section: ReportSection, body: string): string {
  const { start, end } = marker(section);
  const block = `${start}\n## ${SECTION_TITLES[section]}\n\n${body.trim()}\n${end}`;

  const startIndex = existingContent.indexOf(start);
  const endIndex = existingContent.indexOf(end);

  if (startIndex !== -1 && endIndex !== -1 && endIndex > startIndex) {
    return existingContent.slice(0, startIndex) + block + existingContent.slice(endIndex + end.length);
  }

  const separator = existingContent.trim().length > 0 ? '\n\n' : '';
  const header = existingContent.trim().length > 0 ? existingContent.trimEnd() : '# Eval Report';
  return `${header}${separator}${block}\n`;
}

export async function writeReportSection(filePath: string, section: ReportSection, body: string): Promise<void> {
  let existingContent = '';
  try {
    existingContent = await readFile(filePath, 'utf-8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
      throw error;
    }
  }

  const updated = upsertSection(existingContent, section, body);
  await writeFile(filePath, updated, 'utf-8');
}
