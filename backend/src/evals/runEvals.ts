import { fileURLToPath } from 'node:url';
import path from 'node:path';
import request from 'supertest';
import { loadEnv, type Env } from '../env.js';
import { createPool } from '../db.js';
import { createApp } from '../app.js';
import { flushLangfuse } from '../services/observability/langfuse.js';
import { writeReportSection } from './reportWriter.js';
import { testCases, type EvalCase } from './testCases.js';

// Resolved per specs/09's "Open Questions" section (confirmed 2026-07-28): 90% pass rate
// is the bar for "good enough to proceed to Phase 9."
const PASS_RATE_THRESHOLD = 0.9;
const TOP_N = 5;

const REPORT_PATH = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '../../EVAL_REPORT.md');

type StageTiming = { understanding_ms: number; retrieval_ms: number; rerank_ms: number; total_ms: number };

type CaseResult = {
  evalCase: EvalCase;
  passed: boolean;
  missingIncludes: string[];
  unexpectedExcludes: string[];
  error?: string;
  timing?: StageTiming;
};

async function runCase(app: Parameters<typeof request>[0], evalCase: EvalCase): Promise<CaseResult> {
  const response = await request(app).post('/api/search').send({ query: evalCase.query });

  if (response.status !== 200) {
    return {
      evalCase,
      passed: false,
      missingIncludes: evalCase.mustInclude,
      unexpectedExcludes: [],
      error: `HTTP ${response.status}: ${JSON.stringify(response.body)}`,
    };
  }

  const titles: string[] = (response.body.results as Array<{ title: string }>).slice(0, TOP_N).map((r) => r.title);
  const missingIncludes = evalCase.mustInclude.filter((title) => !titles.includes(title));
  const unexpectedExcludes = evalCase.mustExclude.filter((title) => titles.includes(title));

  return {
    evalCase,
    passed: missingIncludes.length === 0 && unexpectedExcludes.length === 0,
    missingIncludes,
    unexpectedExcludes,
    timing: response.body.timing as StageTiming,
  };
}

function average(values: number[]): number {
  if (values.length === 0) {
    return 0;
  }
  return values.reduce((sum, v) => sum + v, 0) / values.length;
}

function buildReportBody(results: CaseResult[], passRate: number): string {
  const passCount = results.filter((r) => r.passed).length;
  const timings = results.map((r) => r.timing).filter((t): t is StageTiming => t !== undefined);

  const lines: string[] = [];
  lines.push(`Generated by \`pnpm --filter backend run eval\` on ${new Date().toISOString()}.`);
  lines.push('');
  lines.push(`**Pass rate: ${passCount}/${results.length} (${(passRate * 100).toFixed(1)}%)** — threshold: ${PASS_RATE_THRESHOLD * 100}%.`);
  lines.push('');
  lines.push('### Average latency per stage (from this run\'s live `/api/search` responses)');
  lines.push('');
  lines.push('| Stage | Avg latency (ms) |');
  lines.push('|---|---|');
  lines.push(`| Query understanding | ${average(timings.map((t) => t.understanding_ms)).toFixed(0)} |`);
  lines.push(`| Retrieval | ${average(timings.map((t) => t.retrieval_ms)).toFixed(0)} |`);
  lines.push(`| Rerank | ${average(timings.map((t) => t.rerank_ms)).toFixed(0)} |`);
  lines.push(`| Total | ${average(timings.map((t) => t.total_ms)).toFixed(0)} |`);
  lines.push('');
  lines.push('### Per-case detail');
  lines.push('');
  lines.push('| Query | Result | Notes |');
  lines.push('|---|---|---|');
  for (const result of results) {
    const notes: string[] = [];
    if (result.missingIncludes.length > 0) {
      notes.push(`missing: ${result.missingIncludes.join(', ')}`);
    }
    if (result.unexpectedExcludes.length > 0) {
      notes.push(`unexpected: ${result.unexpectedExcludes.join(', ')}`);
    }
    if (result.error) {
      notes.push(`error: ${result.error}`);
    }
    const escapedQuery = result.evalCase.query.replace(/\|/g, '\\|');
    lines.push(`| ${escapedQuery} | ${result.passed ? 'PASS' : 'FAIL'} | ${notes.join('; ') || '—'} |`);
  }

  return lines.join('\n');
}

function loadEnvOrExit(): Env {
  try {
    return loadEnv();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}

async function main(): Promise<void> {
  await import('dotenv/config');
  const env = loadEnvOrExit();
  const pool = createPool(env.DATABASE_URL);
  const app = createApp(pool);

  console.log(`Running ${testCases.length} eval cases against the live pipeline (real /api/search calls)...\n`);

  const results: CaseResult[] = [];
  // Sequential, not Promise.all: these are real Claude + Voyage calls sharing the same
  // rate-limited pipeline as a live server, and sequential output is far easier to read.
  for (const evalCase of testCases) {
    const result = await runCase(app, evalCase);
    results.push(result);
    console.log(`${result.passed ? 'PASS' : 'FAIL'}  "${evalCase.query}"`);
    if (!result.passed) {
      if (result.missingIncludes.length > 0) console.log(`  missing: ${result.missingIncludes.join(', ')}`);
      if (result.unexpectedExcludes.length > 0) console.log(`  unexpected: ${result.unexpectedExcludes.join(', ')}`);
      if (result.error) console.log(`  error: ${result.error}`);
    }
  }

  const passCount = results.filter((r) => r.passed).length;
  const passRate = passCount / results.length;
  console.log(`\nPass rate: ${passCount}/${results.length} (${(passRate * 100).toFixed(1)}%)`);

  await writeReportSection(REPORT_PATH, 'EVAL_RESULTS', buildReportBody(results, passRate));
  console.log(`\nWrote eval results to ${REPORT_PATH}`);

  await pool.end();
  await flushLangfuse();

  if (passRate < PASS_RATE_THRESHOLD) {
    console.error(`\nPass rate ${(passRate * 100).toFixed(1)}% is below the ${PASS_RATE_THRESHOLD * 100}% threshold.`);
    process.exitCode = 1;
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
